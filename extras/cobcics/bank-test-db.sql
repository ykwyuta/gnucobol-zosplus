-- Db2 LUW form of reference/Bank-of-Z-main/.setup/jcl/cics/Db2-create.j2.
-- The dedicated schema keeps screen tests separate from other Bank data.
CREATE TABLE BANKZTEST.ACCOUNT (
  ACCOUNT_EYECATCHER CHAR(4),
  ACCOUNT_CUSTOMER_NUMBER CHAR(10),
  ACCOUNT_SORTCODE CHAR(6) NOT NULL,
  ACCOUNT_NUMBER CHAR(8) NOT NULL,
  ACCOUNT_TYPE CHAR(8),
  ACCOUNT_INTEREST_RATE DECIMAL(6,2),
  ACCOUNT_OPENED DATE,
  ACCOUNT_OVERDRAFT_LIMIT INTEGER,
  ACCOUNT_LAST_STATEMENT DATE,
  ACCOUNT_NEXT_STATEMENT DATE,
  ACCOUNT_AVAILABLE_BALANCE DECIMAL(12,2),
  ACCOUNT_ACTUAL_BALANCE DECIMAL(12,2)
);
CREATE UNIQUE INDEX BANKZTEST.ACCTINDX
  ON BANKZTEST.ACCOUNT (ACCOUNT_SORTCODE, ACCOUNT_NUMBER);
CREATE INDEX BANKZTEST.ACCTCUST
  ON BANKZTEST.ACCOUNT (ACCOUNT_SORTCODE, ACCOUNT_CUSTOMER_NUMBER);
CREATE TABLE BANKZTEST.PROCTRAN (
  PROCTRAN_EYECATCHER CHAR(4),
  PROCTRAN_SORTCODE CHAR(6) NOT NULL,
  PROCTRAN_NUMBER CHAR(8) NOT NULL,
  PROCTRAN_DATE DATE,
  PROCTRAN_TIME CHAR(6),
  PROCTRAN_REF CHAR(12),
  PROCTRAN_TYPE CHAR(3),
  PROCTRAN_DESC CHAR(40),
  PROCTRAN_AMOUNT DECIMAL(12,2)
);
CREATE TABLE BANKZTEST.CONTROL (
  CONTROL_NAME CHAR(32),
  CONTROL_VALUE_NUM INTEGER,
  CONTROL_VALUE_STR CHAR(40)
);
CREATE UNIQUE INDEX BANKZTEST.CONTINDX ON BANKZTEST.CONTROL (CONTROL_NAME);
CREATE TABLE BANKZTEST.CUSTOMER (
  CUSTOMER_EYECATCHER CHAR(4),
  CUSTOMER_SORTCODE CHAR(6) NOT NULL,
  CUSTOMER_NUMBER CHAR(10) NOT NULL,
  CUSTOMER_TITLE CHAR(10),
  CUSTOMER_FIRST_NAME CHAR(50),
  CUSTOMER_LAST_NAME CHAR(50),
  CUSTOMER_DATE_OF_BIRTH INTEGER,
  CUSTOMER_PHONE CHAR(20),
  CUSTOMER_ADDR_LINE1 CHAR(50),
  CUSTOMER_ADDR_LINE2 CHAR(50),
  CUSTOMER_CITY CHAR(50),
  CUSTOMER_POSTCODE CHAR(10),
  CUSTOMER_COUNTRY CHAR(50),
  CUSTOMER_STATUS CHAR(10),
  CUSTOMER_CREATED_DATE INTEGER,
  CUSTOMER_CREDIT_SCORE SMALLINT,
  CUSTOMER_CS_REVIEW_DATE INTEGER
);
CREATE UNIQUE INDEX BANKZTEST.CUSTINDX
  ON BANKZTEST.CUSTOMER (CUSTOMER_SORTCODE, CUSTOMER_NUMBER);
CREATE INDEX BANKZTEST.CUSTNAME
  ON BANKZTEST.CUSTOMER (CUSTOMER_LAST_NAME, CUSTOMER_FIRST_NAME);
